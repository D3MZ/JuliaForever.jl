import { mkdtempSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const { SessionManager } = await import(pathToFileURL(join(process.argv[2], "packages/coding-agent/src/core/session-manager.ts")));
const root = mkdtempSync(join(tmpdir(), "jf-pi-fork-"));
const dir = join(root, "sessions");
const user = content => ({ role: "user", content, timestamp: 1 });
const assistant = text => ({ role: "assistant", content: [{ type: "text", text }], api: "openai-completions", provider: "fixture", model: "fixture", stopReason: "stop", timestamp: 2 });
const context = session => session.buildSessionContext().messages.map(message => typeof message.content === "string" ? message.content : message.content.map(part => part.text).join(""));
const source = SessionManager.create(root, dir);
source.appendMessage(user("first"));
const first = source.appendMessage(assistant("reply:first"));
source.appendMessage(user("second"));
source.appendMessage(assistant("reply:second"));
source.branch(first);
source.appendMessage(user("alternative"));
source.appendMessage(assistant("reply:alternative"));
const path = source.getSessionFile();
const before = readFileSync(path, "utf8");
const full = SessionManager.forkFrom(path, root, dir);
const active = SessionManager.open(path, dir);
active.createBranchedSession(active.getLeafId());
const selected = SessionManager.open(path, dir);
selected.createBranchedSession(first);
const queueDir = join(root, "queue");
const queued = SessionManager.create(root, queueDir);
queued.appendMessage(user("first"));
const beforeSteer = queued.appendMessage(assistant("reply:first"));
queued.appendMessage(user("steer"));
const beforeFollow = queued.appendMessage(assistant("reply:steer"));
queued.appendMessage(user("follow"));
queued.appendMessage(assistant("reply:follow"));
const queuePath = queued.getSessionFile();
const steer = SessionManager.open(queuePath, queueDir);
steer.createBranchedSession(beforeSteer);
const follow = SessionManager.open(queuePath, queueDir);
follow.createBranchedSession(beforeFollow);
process.stdout.write(JSON.stringify({ entries: full.getEntries().length, full: context(full), clone: context(active), beforeSecond: context(selected), beforeSteer: context(steer), beforeFollow: context(follow), sourceUnchanged: readFileSync(path, "utf8") === before }));
