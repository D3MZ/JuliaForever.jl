import { join } from "node:path";
import { pathToFileURL } from "node:url";
const source = process.argv[2];
const root = join(source, "packages/coding-agent/src/core");
const { createExtensionRuntime, loadExtensionFromFactory } = await import(pathToFileURL(join(root, "extensions/loader.ts")));
const { ExtensionRunner } = await import(pathToFileURL(join(root, "extensions/runner.ts")));
const { createEventBus } = await import(pathToFileURL(join(root, "event-bus.ts")));
const runtime = createExtensionRuntime();
const bus = createEventBus();
const trace = [];
const errors = [];
const first = await loadExtensionFromFactory(pi => {
  pi.registerTool({ name: "greet", label: "Greet", description: "Greet a person", parameters: { type: "object", properties: { name: { type: "string" } }, required: ["name"] }, execute: async (_id, args) => ({ content: [{ type: "text", text: `Hello, ${args.name}!` }], details: {} }) });
  pi.on("agent_start", () => { trace.push("first"); });
  pi.on("agent_start", () => { trace.push("failure"); throw Error("broken hook"); });
}, process.cwd(), bus, runtime, "first");
const second = await loadExtensionFromFactory(pi => pi.on("agent_start", () => { trace.push("second"); }), process.cwd(), bus, runtime, "second");
const runner = new ExtensionRunner([first, second], runtime, process.cwd(), {}, {});
runner.onError(error => errors.push({ plugin: error.extensionPath, event: error.event, message: error.error }));
await runner.emit({ type: "agent_start" });
const definition = first.tools.get("greet").definition;
const result = await definition.execute("one", { name: "Ada" }, undefined, undefined, runner.createToolContext("one", undefined));
process.stdout.write(JSON.stringify({ trace, errors, name: definition.name, description: definition.description, parameters: definition.parameters, result: result.content[0].text }));
