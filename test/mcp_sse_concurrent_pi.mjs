import { pathToFileURL } from "node:url";

const { StreamableHttpTransport } = await import(pathToFileURL(`${process.env.PI_SOURCE}/packages/mcp/src/index.ts`).href);
const deadline = setTimeout(() => process.exit(2), 15000);
const transport = new StreamableHttpTransport({ url: process.env.JF_HTTP_URL, openGetStream: false, reconnect: { maxRetries: 0 } });
const pending = new Map();
const errors = [];
transport.onMessage(message => pending.get(message.id)?.(message.result));
transport.onError(error => errors.push(error.name));
await transport.start();
const first = new Promise(resolve => pending.set(1, resolve));
const second = new Promise(resolve => pending.set(2, resolve));
await transport.send({ jsonrpc: "2.0", id: 1, method: "first", params: {} });
await transport.send({ jsonrpc: "2.0", id: 2, method: "second", params: {} });
const timer = setTimeout(() => process.exit(2), 10000);
const results = await Promise.all([first, second]);
clearTimeout(timer);
await fetch(`${process.env.JF_HTTP_URL}/release`, { method: "POST" });
await transport.close();
clearTimeout(deadline);
process.stdout.write(JSON.stringify({ results, errors: errors.length }));
