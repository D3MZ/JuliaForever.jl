import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';
import { register } from 'node:module';
register('./tool_options_loader.mjs', import.meta.url);
const [source, input] = process.argv.slice(2);
const {cwd, agentDir} = JSON.parse(readFileSync(input, 'utf8'));
const core = join(source, 'packages/coding-agent/src/core');
const load = file => import(pathToFileURL(join(core, file)));
const { createAgentSession } = await load('sdk.ts');
const { SettingsManager } = await load('settings-manager.ts');
const { DefaultResourceLoader } = await load('resource-loader.ts');
const { SessionManager } = await load('session-manager.ts');
const { buildSystemPromptSections } = await load('system-prompt.ts');
const settingsManager = SettingsManager.inMemory();
const resourceLoader = new DefaultResourceLoader({cwd, agentDir, settingsManager, noExtensions:true, noPromptTemplates:true, noThemes:true, noContextFiles:true});
await resourceLoader.reload();
const model = {id:'fixture', name:'fixture', api:'openai-completions', provider:'fixture', baseUrl:'http://localhost', reasoning:false, input:['text'], cost:{input:0, output:0, cacheRead:0, cacheWrite:0}, contextWindow:8192, maxTokens:1024};
const output = [];
for (const tools of [undefined, [], ['write'], ['bash'], ['read'], ['read','bash']]) {
  const manager = SessionManager.inMemory(cwd);
  const {session} = await createAgentSession({cwd, agentDir, model, settingsManager, resourceLoader, sessionManager:manager, tools});
  const view = () => ({section: session.systemPrompt.match(/<skills>\n[\s\S]*?<\/skills>/)?.[0] ?? null, expanded: session._expandSkillCommand('/skill:example hello')});
  const initial = view();
  await session.reload();
  const reloaded = view();
  manager.appendMessage({role:'user', content:[{type:'text', text:'prior'}], timestamp:1});
  session.dispose();
  const resumed = await createAgentSession({cwd, agentDir, model, settingsManager, resourceLoader, sessionManager:manager, tools});
  output.push({initial, reloaded, resumed: {section: resumed.session.systemPrompt.match(/<skills>\n[\s\S]*?<\/skills>/)?.[0] ?? null, expanded: resumed.session._expandSkillCommand('/skill:example hello')}});
  resumed.session.dispose();
}
const {session: changed} = await createAgentSession({cwd, agentDir, model, settingsManager, resourceLoader, sessionManager:SessionManager.inMemory(cwd), tools:['read']});
changed.sessionManager.appendMessage({role:'user', content:[{type:'text', text:'prior'}], timestamp:1});
const saved = changed.sessionManager;
changed.dispose();
const reopened = await createAgentSession({cwd, agentDir, model, settingsManager, resourceLoader, sessionManager:saved, tools:[]});
output.push({resumedWithoutReader: reopened.session.systemPrompt.includes('<available_skills>')});
reopened.session.dispose();
output.push({hidden: buildSystemPromptSections({cwd, skills:resourceLoader.getSkills().skills, selectedTools:['bash'], hiddenTools:['bash']}).skills});
const changes = [];
for (const tools of [[], ['bash'], ['read'], ['read','bash']]) {
  const manager = SessionManager.inMemory(cwd);
  const {session: first} = await createAgentSession({cwd, agentDir, model, settingsManager, resourceLoader, sessionManager:manager, tools:['read']});
  manager.appendMessage({role:'user', content:[{type:'text', text:'prior'}], timestamp:1});
  first.dispose();
  const {session} = await createAgentSession({cwd, agentDir, model, settingsManager, resourceLoader, sessionManager:manager, tools});
  changes.push({section: session.systemPrompt.match(/<skills>\n[\s\S]*?<\/skills>/)?.[0] ?? null, expanded: session._expandSkillCommand('/skill:example hello')});
  session.dispose();
}
output.push({changes});
process.stdout.write(JSON.stringify(output));
