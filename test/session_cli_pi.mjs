import { join } from "node:path";
import { pathToFileURL } from "node:url";

const [source, cwd, other, dir] = process.argv.slice(2);
const { SessionManager } = await import(pathToFileURL(join(source, "packages/coding-agent/src/core/session-manager.ts")));
const pause = () => new Promise((resolve) => setTimeout(resolve, 10));
const message = (text) => ({ role: "user", content: text, timestamp: Date.now() });
const first = SessionManager.create(cwd, dir);
first.appendMessage(message("first"));
await pause();
const second = SessionManager.create(cwd, dir);
second.appendMessage(message("third"));
await pause();
SessionManager.open(first.getSessionFile()).appendMessage(message("fifth"));
await pause();
SessionManager.open(second.getSessionFile()).appendMessage(message("seventh"));
await pause();
SessionManager.create(other, dir).appendMessage(message("elsewhere"));
const local = await SessionManager.list(cwd, dir);
const recent = SessionManager.continueRecent(cwd, dir).getSessionFile();
const elsewhere = await SessionManager.list(other, dir);
process.stdout.write(JSON.stringify({ titles: local.map((session) => session.firstMessage), recent: local.find((session) => session.path === recent)?.firstMessage, other: elsewhere.map((session) => session.firstMessage) }));
