function instructioncases(dir)
    cases = []
    agent = joinpath(dir, "empty-agent")
    mkpath(agent)
    add(label, cwd, expected; agentdir=agent) = push!(cases, (; label, cwd, agentdir, expected))
    entry(directory, name, content) = (; path=joinpath(directory, name), content)
    function file(directory, name, content)
        mkpath(directory)
        write(joinpath(directory, name), content)
    end
    function nested(name)
        main = joinpath(dir, name, "main")
        worktree = joinpath(main, "worktrees", "feature")
        leaf = joinpath(worktree, "src")
        gitdir = joinpath(main, ".git", "worktrees", "feature")
        mkpath(leaf)
        file(joinpath(main, ".git"), "HEAD", "ref: refs/heads/main\n")
        file(gitdir, "HEAD", "ref: refs/heads/feature\n")
        file(gitdir, "commondir", "../..")
        file(worktree, ".git", "gitdir: $gitdir\n")
        (; main, worktree, leaf)
    end

    empty = joinpath(dir, "empty")
    mkpath(empty)
    add("empty", empty, [])

    globaldir = joinpath(dir, "global")
    project = joinpath(dir, "layered")
    service = joinpath(project, "service")
    leaf = joinpath(service, "leaf")
    file(globaldir, "AGENTS.override.md", "\ufeffglobal 🌱\n")
    file(globaldir, "AGENTS.md", "ignored global")
    file(project, "AGENTS.md", "project\n")
    file(project, "CLAUDE.md", "ignored project")
    file(service, "AGENTS.override.md", "")
    file(service, "AGENTS.md", "ignored service")
    file(leaf, "CLAUDE.md", "\ufefffallback\n")
    add("global, precedence, ancestors, empty and BOM", leaf, [entry(globaldir, "AGENTS.override.md", "global 🌱\n"), entry(project, "AGENTS.md", "project\n"), entry(service, "AGENTS.override.md", ""), entry(leaf, "CLAUDE.md", "fallback\n")]; agentdir=globaldir)
    add("global ancestor is deduplicated and stays first", leaf, [entry(service, "AGENTS.override.md", ""), entry(project, "AGENTS.md", "project\n"), entry(leaf, "CLAUDE.md", "fallback\n")]; agentdir=service)
    add("relative paths", relpath(leaf), [entry(globaldir, "AGENTS.override.md", "global 🌱\n"), entry(project, "AGENTS.md", "project\n"), entry(service, "AGENTS.override.md", ""), entry(leaf, "CLAUDE.md", "fallback\n")]; agentdir=relpath(globaldir))

    fallback = joinpath(dir, "fallback")
    mkpath(joinpath(fallback, "AGENTS.override.md"))
    mkpath(joinpath(fallback, "AGENTS.md"))
    file(fallback, "CLAUDE.md", "directory fallback")
    add("directory candidates are skipped", fallback, [entry(fallback, "CLAUDE.md", "directory fallback")])

    upper = joinpath(dir, "upper")
    file(upper, "AGENTS.MD", "upper agents")
    uppername = isfile(joinpath(upper, "AGENTS.md")) ? "AGENTS.md" : "AGENTS.MD"
    add("uppercase AGENTS suffix", upper, [entry(upper, uppername, "upper agents")])
    upperclaude = joinpath(dir, "upper-claude")
    file(upperclaude, "CLAUDE.MD", "upper claude")
    upperclaudename = isfile(joinpath(upperclaude, "CLAUDE.md")) ? "CLAUDE.md" : "CLAUDE.MD"
    add("uppercase CLAUDE suffix", upperclaude, [entry(upperclaude, upperclaudename, "upper claude")])

    work = nested("nested")
    file(work.main, "AGENTS.md", "main")
    file(work.worktree, "AGENTS.md", "worktree")
    file(work.leaf, "AGENTS.md", "leaf")
    add("nested linked worktree shadows same filename", work.leaf, [entry(work.worktree, "AGENTS.md", "worktree"), entry(work.leaf, "AGENTS.md", "leaf")])
    add("global file survives worktree shadowing", work.leaf, [entry(work.main, "AGENTS.md", "main"), entry(work.worktree, "AGENTS.md", "worktree"), entry(work.leaf, "AGENTS.md", "leaf")]; agentdir=work.main)

    different = nested("different")
    file(different.main, "CLAUDE.md", "main claude")
    file(different.worktree, "AGENTS.md", "worktree agents")
    add("worktree shadows only matching names", different.leaf, [entry(different.main, "CLAUDE.md", "main claude"), entry(different.worktree, "AGENTS.md", "worktree agents")])

    inherited = nested("inherited")
    file(inherited.main, "AGENTS.md", "inherited")
    add("no worktree file inherits main", inherited.leaf, [entry(inherited.main, "AGENTS.md", "inherited")])

    ordinary = joinpath(dir, "ordinary")
    repo = joinpath(ordinary, "repo")
    ordinaryleaf = joinpath(repo, "src")
    file(ordinary, "AGENTS.md", "outside repo")
    file(joinpath(repo, ".git"), "HEAD", "ref: refs/heads/main\n")
    file(repo, "AGENTS.md", "inside repo")
    file(ordinaryleaf, "AGENTS.md", "ordinary leaf")
    add("walks past an ordinary Git root", ordinaryleaf, [entry(ordinary, "AGENTS.md", "outside repo"), entry(repo, "AGENTS.md", "inside repo"), entry(ordinaryleaf, "AGENTS.md", "ordinary leaf")])

    relativegit = nested("relative-git")
    file(relativegit.worktree, ".git", "gitdir: ../../.git/worktrees/feature\n")
    file(relativegit.main, "AGENTS.md", "relative main")
    file(relativegit.worktree, "AGENTS.md", "relative worktree")
    add("relative linked worktree metadata", relativegit.leaf, [entry(relativegit.worktree, "AGENTS.md", "relative worktree")])

    bad = joinpath(dir, "invalid-git")
    badleaf = joinpath(bad, "src")
    mkpath(badleaf)
    file(bad, ".git", "gitdir: /nonexistent/jf-missing\n")
    file(bad, "AGENTS.md", "invalid git")
    file(badleaf, "AGENTS.md", "invalid git leaf")
    add("invalid git metadata still walks ancestors", badleaf, [entry(bad, "AGENTS.md", "invalid git"), entry(badleaf, "AGENTS.md", "invalid git leaf")])

    bare = joinpath(dir, "bare")
    baregit = joinpath(bare, ".bare")
    barework = joinpath(bare, "main")
    bareworkgit = joinpath(baregit, "worktrees", "main")
    file(baregit, "HEAD", "ref: refs/heads/main\n")
    file(bareworkgit, "HEAD", "ref: refs/heads/main\n")
    file(bareworkgit, "commondir", "../..")
    file(barework, ".git", "gitdir: $bareworkgit\n")
    file(bare, "AGENTS.md", "container")
    file(barework, "AGENTS.md", "bare worktree")
    add("bare container is not shadowed", barework, [entry(bare, "AGENTS.md", "container"), entry(barework, "AGENTS.md", "bare worktree")])

    if !Sys.iswindows()
        linked = nested("symlink")
        file(linked.main, "AGENTS.md", "linked")
        symlink(joinpath(linked.main, "AGENTS.md"), joinpath(linked.worktree, "AGENTS.md"))
        add("worktree symlink retains worktree path", linked.leaf, [entry(linked.worktree, "AGENTS.md", "linked")])
        alias = joinpath(dir, "alias")
        symlink(project, alias)
        add("lexical symlink paths", joinpath(alias, "service", "leaf"), [entry(alias, "AGENTS.md", "project\n"), entry(joinpath(alias, "service"), "AGENTS.override.md", ""), entry(joinpath(alias, "service", "leaf"), "CLAUDE.md", "fallback\n")])
        add("different lexical paths retain shared file", joinpath(alias, "service", "leaf"), [entry(project, "AGENTS.md", "project\n"), entry(alias, "AGENTS.md", "project\n"), entry(joinpath(alias, "service"), "AGENTS.override.md", ""), entry(joinpath(alias, "service", "leaf"), "CLAUDE.md", "fallback\n")]; agentdir=project)
    end
    cases
end
