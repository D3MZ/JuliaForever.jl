import { pathToFileURL } from "node:url";
const { StreamableHttpTransport } = await import(pathToFileURL(`${process.env.PI_SOURCE}/packages/mcp/src/index.ts`).href);
const transport = new StreamableHttpTransport({ url: process.env.JF_HTTP_URL, headers: { Authorization: "Bearer secret" } });
let resolve;
const answer = new Promise(r => resolve = r);
transport.onMessage(message => { if (message.id === 2) resolve(message.result); });
transport.onError(() => {});
await transport.start();
await transport.send({ jsonrpc: "2.0", method: "notifications/initialized" });
await transport.send({ jsonrpc: "2.0", id: 2, method: "probe", params: {} });
console.log(JSON.stringify(await Promise.race([answer, new Promise(r => setTimeout(() => r(null), 2000))])));
await new Promise(r => setTimeout(r, 100));
await transport.close();
